#!/usr/bin/env python
"""
Generate a synthetic Liga store so the pipeline can be exercised without Sofascore.

Sofascore is unreachable from CI and from most sandboxes, so without this there is no
way to run or test the build before the first real fetch lands. The output is
structurally identical to what fetch_sofascore_liga.py writes — same keys, same
statuses, same date format — but the results are simulated from fixed club strengths.

This is a development aid. It writes to a path you name, and the real store is only
ever produced by the fetcher.

    python scripts/make_liga_sample_store.py docs/liga/data/liga_store.json
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT))

from oddsmarkets.football.competitions.liga.config import (  # noqa: E402
    APERTURA,
    CLAUSURA,
    FALLBACK_ZONES_2026,
    ZONES,
)

# Rough relative attacking strength, used only to make the synthetic table look
# plausible rather than uniform. Not a claim about the real clubs.
STRENGTH = {
    "River Plate": 1.55, "Boca Juniors": 1.50, "Racing Club": 1.45, "Vélez Sarsfield": 1.40,
    "Talleres": 1.38, "Estudiantes": 1.35, "Independiente": 1.33, "San Lorenzo": 1.30,
    "Lanús": 1.28, "Huracán": 1.26, "Belgrano": 1.30, "Rosario Central": 1.32,
    "Argentinos Juniors": 1.25, "Defensa y Justicia": 1.24, "Godoy Cruz": 1.20,
    "Newell's Old Boys": 1.22, "Tigre": 1.15, "Platense": 1.12, "Banfield": 1.16,
    "Instituto": 1.14, "Barracas Central": 1.13, "Central Córdoba": 1.18,
    "Gimnasia LP": 1.17, "Atlético Tucumán": 1.15, "Unión": 1.14,
    "Independiente Rivadavia": 1.10, "Sarmiento": 1.05, "Deportivo Riestra": 1.08,
    "Aldosivi": 1.00, "San Martín SJ": 0.98,
}
HOME_BOOST = 1.25


def _score(rng, home: str, away: str) -> tuple[int, int]:
    lam_h = STRENGTH.get(home, 1.2) / STRENGTH.get(away, 1.2) * HOME_BOOST
    lam_a = STRENGTH.get(away, 1.2) / STRENGTH.get(home, 1.2)
    return int(rng.poisson(lam_h)), int(rng.poisson(lam_a))


def _fixtures(zones: dict[str, list[str]], torneo: str, start_gid: int):
    """Single round-robin per zone plus two interzone matches per club."""
    out = []
    gid = start_gid
    for zone in ZONES:
        members = zones[zone]
        for i in range(len(members)):
            for j in range(i + 1, len(members)):
                gid += 1
                home, away = (members[i], members[j]) if (i + j) % 2 == 0 else (members[j], members[i])
                out.append({
                    "gid": gid, "home": home, "away": away,
                    "round": (i + j) % 14 + 1, "zone": zone, "torneo": torneo,
                })
    # Interzone: pair each Zona A club with the Zona B club at the same index, twice.
    for leg in range(2):
        for idx, home in enumerate(zones[ZONES[0]]):
            away = zones[ZONES[1]][(idx + leg) % len(zones[ZONES[1]])]
            gid += 1
            h, a = (home, away) if leg == 0 else (away, home)
            out.append({
                "gid": gid, "home": h, "away": a,
                "round": 15 + leg, "zone": None, "torneo": torneo,
            })
    return out, gid


def build(played_rounds: int = 5, seed: int = 11) -> dict:
    rng = np.random.default_rng(seed)
    zones = {z: list(FALLBACK_ZONES_2026[z]) for z in ZONES}
    store = {
        "matches": {}, "lineups": {}, "shots": {}, "momentum": {}, "incidents": {},
        "zones": {APERTURA: zones, CLAUSURA: zones},
        "meta": {
            "updated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            # Marks this store as generated rather than fetched. The build reads it
            # and labels the site accordingly, so simulated results can never be
            # mistaken for real ones just because they look plausible.
            "synthetic": True,
            "note": "Generated by scripts/make_liga_sample_store.py — not real match data.",
        },
    }

    apertura_start = datetime(2026, 1, 22, tzinfo=timezone.utc)
    clausura_start = datetime(2026, 7, 23, tzinfo=timezone.utc)

    apertura, gid = _fixtures(zones, APERTURA, 0)
    for f in apertura:
        hg, ag = _score(rng, f["home"], f["away"])
        date = apertura_start + timedelta(days=f["round"] * 7 + int(rng.integers(0, 3)))
        store["matches"][str(f["gid"])] = {
            "home": f["home"], "away": f["away"], "round": f["round"],
            "status": "Ended", "hs": hg, "as": ag,
            "date": date.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "torneo": APERTURA, "zone": f["zone"], "season_id": 70001,
        }

    clausura, gid = _fixtures(zones, CLAUSURA, gid)
    for f in clausura:
        done = f["round"] <= played_rounds
        hg, ag = _score(rng, f["home"], f["away"]) if done else (None, None)
        date = clausura_start + timedelta(days=f["round"] * 7 + int(rng.integers(0, 3)))
        store["matches"][str(f["gid"])] = {
            "home": f["home"], "away": f["away"], "round": f["round"],
            "status": "Ended" if done else "Not started",
            "hs": hg, "as": ag,
            "date": date.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "torneo": CLAUSURA, "zone": f["zone"], "season_id": 70002,
        }

    # Player-level detail, so xG, shot maps, momentum and the Players tab have input.
    #
    # Squads are built once per club with STABLE player ids, the way Sofascore returns
    # them. An earlier version generated ids per match, which silently turned each real
    # player into one row per appearance — the season aggregation then produced
    # thousands of one-match players and the top-scorer probabilities summed to 6
    # instead of 1. Stable identity across matches is the whole point of the id.
    squads: dict[str, list[dict]] = {}
    for zone in ZONES:
        for team in zones[zone]:
            slug = team.lower().replace(" ", "-").replace("'", "")
            squad = []
            for n in range(18):
                role = "FWD" if n < 4 else "MID" if n < 10 else "DEF" if n < 16 else "GK"
                squad.append({
                    "id": f"p-{slug}-{n:02d}",
                    "name": f"{slug}-{role}{n + 1}",
                    "role": role,
                    "quality": float(rng.uniform(0.5, 1.5)),
                })
            squads[team] = squad

    # Cover every finished match of the live tournament, plus a slice of the completed
    # one. Taking the first N of a flat list instead would put all the detail in the
    # Apertura, leaving the Clausura with no xG at all — which silently zeroed the
    # xG-difference and luck columns, since those describe the live tournament.
    finished_live = [
        g for g, m in store["matches"].items()
        if m["status"] == "Ended" and m["torneo"] == CLAUSURA
    ]
    finished_past = [
        g for g, m in store["matches"].items()
        if m["status"] == "Ended" and m["torneo"] == APERTURA
    ]
    for gid_s in finished_live + finished_past[:120]:
        meta = store["matches"][gid_s]
        players = {}
        shots = []
        incidents = []

        for side, team in (("h", meta["home"]), ("a", meta["away"])):
            is_home = side == "h"
            scored = meta["hs"] if is_home else meta["as"]
            squad = squads[team]
            # 11 starters plus 3 substitutes, drawn stably so the same faces recur.
            playing = squad[:11] + list(rng.choice(squad[11:], size=3, replace=False))

            for p in playing:
                gk = p["role"] == "GK"
                mins = 90.0 if p in squad[:11] else float(rng.integers(10, 35))
                xg = 0.0 if gk else round(float(rng.gamma(1.2, 0.10) * p["quality"]), 3)
                players[p["id"]] = {
                    "n": p["name"],
                    "t": team,
                    "s": {
                        "minutesPlayed": mins,
                        "goals": 0.0,
                        "goalAssist": 0.0,
                        "expectedGoals": xg,
                        "expectedAssists": round(float(rng.gamma(1.0, 0.07)), 3),
                        "expectedGoalsOnTarget": round(xg * 0.8, 3),
                        "totalShots": 0.0 if gk else float(rng.integers(0, 5)),
                        "onTargetScoringAttempt": 0.0 if gk else float(rng.integers(0, 3)),
                        "keyPass": float(rng.integers(0, 4)),
                        "bigChanceCreated": float(rng.integers(0, 2)),
                        "accuratePass": float(rng.integers(20, 60)),
                        "totalPass": float(rng.integers(30, 75)),
                        "duelWon": float(rng.integers(1, 9)),
                        "duelLost": float(rng.integers(1, 8)),
                        "wonTackle": float(rng.integers(0, 5)),
                        "interceptionWon": float(rng.integers(0, 4)),
                        "ballRecovery": float(rng.integers(1, 9)),
                        "touches": float(rng.integers(25, 95)),
                        "saves": float(rng.integers(1, 6)) if gk else 0.0,
                        "goalsPrevented": round(float(rng.normal(0, 0.4)), 2) if gk else 0.0,
                        "kilometersCovered": round(float(rng.normal(9.6, 1.1)), 1),
                        "numberOfSprints": float(rng.integers(10, 35)),
                        "topSpeed": round(float(rng.normal(31, 2)), 1),
                        "rating": round(float(np.clip(rng.normal(6.8, 0.7), 4.0, 9.8)), 2),
                    },
                }

            # Attribute the match's goals to outfield players, and log an incident for
            # each so the match timeline has something to draw.
            scorers = [p for p in playing if p["role"] != "GK"]
            for _ in range(int(scored or 0)):
                s = scorers[int(rng.integers(0, len(scorers)))]
                players[s["id"]]["s"]["goals"] += 1.0
                incidents.append({
                    "incident_type": "goal", "incident_class": "regular",
                    "time": int(rng.integers(1, 91)),
                    "is_home": is_home, "player_name": s["name"],
                })

            # Shot coordinates on a 0-100 pitch, clustered toward the penalty area.
            for p in playing:
                if p["role"] == "GK":
                    continue
                for _ in range(int(rng.integers(0, 4))):
                    shots.append({
                        "player_name": p["name"],
                        "team": team,
                        "is_home": is_home,
                        "x": round(float(np.clip(rng.normal(84, 9), 50, 99)), 1),
                        "y": round(float(np.clip(rng.normal(50, 13), 2, 98)), 1),
                        "xg": round(float(rng.gamma(1.1, 0.09)), 3),
                        "xgot": round(float(rng.gamma(1.0, 0.07)), 3),
                        "shot_type": str(rng.choice(["goal", "save", "miss", "block"])),
                        "body_part": str(rng.choice(["right-foot", "left-foot", "head"])),
                        "situation": str(rng.choice(["open-play", "corner", "free-kick"])),
                        "time": int(rng.integers(1, 91)),
                    })

        for _ in range(int(rng.integers(1, 4))):
            incidents.append({
                "incident_type": "card", "incident_class": "yellow",
                "time": int(rng.integers(1, 91)),
                "is_home": bool(rng.integers(0, 2)),
                "player_name": squads[meta["home"]][int(rng.integers(0, 11))]["name"],
            })

        store["lineups"][gid_s] = players
        store["shots"][gid_s] = shots
        store["incidents"][gid_s] = sorted(incidents, key=lambda i: i["time"])
        # Momentum: pressure swinging between sides across the 90 minutes.
        store["momentum"][gid_s] = [
            {"minute": m, "value": round(float(np.clip(rng.normal(0, 45), -100, 100)), 1)}
            for m in range(0, 91, 5)
        ]

    return store


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("out", type=Path)
    parser.add_argument("--rounds", type=int, default=5, help="Clausura rounds played")
    parser.add_argument("--seed", type=int, default=11)
    args = parser.parse_args()

    store = build(args.rounds, args.seed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(store, ensure_ascii=False), encoding="utf-8")
    finished = sum(1 for m in store["matches"].values() if m["status"] == "Ended")
    print(
        f"wrote {args.out}: {len(store['matches'])} matches "
        f"({finished} finished), {len(store['lineups'])} with player detail"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
