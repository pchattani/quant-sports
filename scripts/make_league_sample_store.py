#!/usr/bin/env python
"""
Generate a synthetic store for one competition so the pipeline can be exercised
without Sofascore.

Structurally identical to what fetch_sofascore_leagues.py writes — same keys, same
status values, two seasons under distinct ids, conferences for MLS, groups or
regions for the cups, per-match detail in the full format (lineups with positions
and shirt numbers, player metadata, the team-stat sheet, shots with player ids,
incidents, momentum) — but results are simulated from made-up club strengths and
the store is marked `synthetic`, which the build surfaces as a banner. A
development aid: it writes to a path you name and the real store only ever comes
from the fetcher.

    python scripts/make_league_sample_store.py premier-league /tmp/epl_store.json
    python scripts/make_league_sample_store.py mls out.json --rounds 20
    python scripts/make_league_sample_store.py afc-champions-league out.json --rounds 3
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT))

from oddsmarkets.football.competitions.cup.config import CUPS, CupConfig  # noqa: E402
from oddsmarkets.football.competitions.league.config import LEAGUES, LeagueConfig  # noqa: E402

SEASONS_PATH = ROOT / "oddsmarkets" / "football" / "competitions" / "league" / "data" / "seasons.json"

STAMP = "%Y-%m-%dT%H:%M:%SZ"


def team_names(cfg: LeagueConfig) -> tuple[list[str], dict[str, list[str]]]:
    """Real club names from the discovery file when present, placeholders otherwise."""
    if SEASONS_PATH.exists():
        try:
            entry = json.loads(SEASONS_PATH.read_text(encoding="utf-8"))["leagues"].get(cfg.slug)
        except Exception:  # noqa: BLE001
            entry = None
        if entry and len(entry.get("teams") or []) == cfg.n_teams:
            confs = entry.get("conferences") or {}
            if not cfg.conferences or all(len(confs.get(c, [])) == cfg.teams_per_conference for c in cfg.conferences):
                return list(entry["teams"]), {c: list(confs[c]) for c in (cfg.conferences or ())}
    teams = [f"{cfg.short_name} Club {i + 1:02d}" for i in range(cfg.n_teams)]
    confs = {}
    if cfg.conferences:
        per = cfg.teams_per_conference
        confs = {c: teams[k * per:(k + 1) * per] for k, c in enumerate(cfg.conferences)}
    return teams, confs


def _double_round_robin(teams: list[str]) -> list[tuple[int, str, str]]:
    """(round, home, away) for every ordered pair, round-robin ordered by a circle method."""
    n = len(teams)
    order = list(teams)
    if n % 2:
        order.append(None)
        n += 1
    rounds = []
    for r in range(n - 1):
        pairs = []
        for i in range(n // 2):
            a, b = order[i], order[n - 1 - i]
            if a is None or b is None:
                continue
            pairs.append((a, b) if (r + i) % 2 == 0 else (b, a))
        rounds.append(pairs)
        order = [order[0]] + [order[-1]] + order[1:-1]
    out = []
    for r, pairs in enumerate(rounds):
        for h, a in pairs:
            out.append((r + 1, h, a))
    for r, pairs in enumerate(rounds):
        for h, a in pairs:
            out.append((len(rounds) + r + 1, a, h))
    return out


def _empty_store(slug: str, name: str, confs: dict) -> dict:
    return {
        "matches": {}, "lineups": {}, "shots": {}, "momentum": {}, "incidents": {},
        "players": {}, "team_stats": {}, "lineup_extras": {},
        "conferences": confs,
        "meta": {
            "updated_at": datetime.now(timezone.utc).strftime(STAMP),
            "synthetic": True,
            "note": "Generated by scripts/make_league_sample_store.py — not real match data.",
            "league": slug, "season_id": 900002, "season_name": f"{name} sample",
        },
    }


# Squad slots: a starting eleven in a 4-4-2 (goalkeeper first), then a bench of
# seven — the shape the lineups reader expects (starters, keeper on top).
_ROLES = ["GK"] + ["DEF"] * 4 + ["MID"] * 4 + ["FWD"] * 2 + ["GK", "DEF", "DEF", "MID", "MID", "FWD", "FWD"]
_POS = {"GK": "G", "DEF": "D", "MID": "M", "FWD": "F"}


def _squads(teams: list[str], rng) -> dict[str, list[dict]]:
    squads: dict[str, list[dict]] = {}
    for n, team in enumerate(teams):
        slug = "".join(ch for ch in team.lower() if ch.isalnum() or ch == " ").replace(" ", "-")
        squads[team] = [{
            "id": str(700000 + n * 100 + k),
            "name": f"{slug}-{role}{k + 1}",
            "role": role,
            "pos": _POS[role],
            "quality": float(rng.uniform(0.5, 1.5)),
            "dob": int(datetime(1990 + int(rng.integers(0, 17)), 1 + int(rng.integers(0, 12)), 1 + int(rng.integers(0, 28)), tzinfo=timezone.utc).timestamp()),
            "height": int(rng.integers(168, 196)),
        } for k, role in enumerate(_ROLES)]
    return squads


def _sheet(rng, xg: float, shots: int) -> dict:
    passes = int(rng.integers(300, 650))
    acc = int(passes * rng.uniform(0.72, 0.92))
    return {
        "ballPossession": int(rng.integers(35, 66)), "expectedGoals": round(xg, 2),
        "totalShotsOnGoal": shots, "shotsOnGoal": int(shots * rng.uniform(0.25, 0.5)),
        "cornerKicks": int(rng.integers(1, 10)), "fouls": int(rng.integers(6, 16)),
        "passes": passes, "accuratePasses": acc, "totalTackle": int(rng.integers(10, 24)),
        "interceptionWon": int(rng.integers(4, 14)), "ballRecovery": int(rng.integers(30, 60)),
        "totalClearance": int(rng.integers(8, 32)), "touchesInOppBox": int(rng.integers(8, 32)),
        "finalThirdEntries": int(rng.integers(30, 75)), "yellowCards": int(rng.integers(0, 4)),
        "goalkeeperSaves": int(rng.integers(0, 7)), "kilometersCovered": round(float(rng.normal(112, 4)), 1),
        "numberOfSprints": int(rng.integers(110, 170)), "avgRating": round(float(rng.normal(6.9, 0.3)), 2),
        "aerialDuelsPercentage": int(rng.integers(5, 20)), "aerialDuelsPercentage_total": 24,
        "groundDuelsPercentage": int(rng.integers(25, 45)), "groundDuelsPercentage_total": 70,
        "accurateLongBalls": int(rng.integers(10, 30)), "accurateLongBalls_total": int(rng.integers(35, 60)),
    }


def add_detail(store: dict, gid: str, meta: dict, squads: dict, rng) -> None:
    """Full-format detail for one finished match."""
    players, shots, incidents = {}, [], []
    sheet = {}
    for side, team in (("home", meta["home"]), ("away", meta["away"])):
        is_home = side == "home"
        scored = meta["hs"] if is_home else meta["as"]
        squad = squads[team]
        playing = squad[:11] + list(rng.choice(squad[11:], size=3, replace=False))
        team_xg, team_shots = 0.0, 0
        for p in playing:
            gk = p["role"] == "GK"
            starter = p in squad[:11]
            mins = 90.0 if starter else float(rng.integers(10, 35))
            xg = 0.0 if gk else round(float(rng.gamma(1.2, 0.10) * p["quality"]), 3)
            n_shots = 0 if gk else int(rng.integers(0, 5))
            team_xg += xg
            team_shots += n_shots
            players[p["id"]] = {"n": p["name"], "t": team, "p": p["pos"], "no": str(squad.index(p) + 1), **({"sub": True} if not starter else {}), "s": {
                "minutesPlayed": int(mins), "goals": 0, "goalAssist": 0,
                "expectedGoals": xg, "expectedAssists": round(float(rng.gamma(1.0, 0.07)), 3),
                "expectedGoalsOnTarget": round(xg * 0.8, 3),
                "totalShots": n_shots, "onTargetScoringAttempt": int(rng.integers(0, n_shots + 1)),
                "keyPass": int(rng.integers(0, 4)), "bigChanceCreated": int(rng.integers(0, 2)),
                "accuratePass": int(rng.integers(20, 60)), "totalPass": int(rng.integers(60, 75)),
                "accurateOppositionHalfPasses": int(rng.integers(5, 30)),
                "accurateLongBalls": int(rng.integers(0, 6)), "totalLongBalls": int(rng.integers(6, 10)),
                "accurateCross": int(rng.integers(0, 3)), "totalCross": int(rng.integers(3, 6)),
                "wonContest": int(rng.integers(0, 4)), "totalContest": int(rng.integers(4, 7)),
                "ballCarriesCount": int(rng.integers(10, 40)), "progressiveBallCarriesCount": int(rng.integers(0, 8)),
                "totalBallCarriesDistance": int(rng.integers(100, 500)),
                "duelWon": int(rng.integers(1, 9)), "duelLost": int(rng.integers(1, 8)),
                "aerialWon": int(rng.integers(0, 5)), "aerialLost": int(rng.integers(0, 4)),
                "wonTackle": int(rng.integers(0, 5)), "totalTackle": int(rng.integers(5, 8)),
                "interceptionWon": int(rng.integers(0, 4)), "totalClearance": int(rng.integers(0, 6)),
                "outfielderBlock": int(rng.integers(0, 3)), "ballRecovery": int(rng.integers(1, 9)),
                "touches": int(rng.integers(25, 95)), "dispossessed": int(rng.integers(0, 3)),
                "possessionLostCtrl": int(rng.integers(4, 16)), "fouls": int(rng.integers(0, 3)),
                "wasFouled": int(rng.integers(0, 3)),
                "saves": int(rng.integers(1, 6)) if gk else 0,
                "goalsPrevented": round(float(rng.normal(0, 0.4)), 2) if gk else 0,
                "totalKeeperSweeper": int(rng.integers(0, 3)) if gk else 0,
                "kilometersCovered": round(float(rng.normal(9.6, 1.1)), 1),
                "metersCoveredHighSpeedRunningKm": round(float(rng.normal(0.7, 0.2)), 2),
                "numberOfSprints": int(rng.integers(10, 35)),
                "topSpeed": round(float(rng.normal(31, 2)), 1),
                "rating": round(float(np.clip(rng.normal(6.8, 0.7), 4.0, 9.8)), 2),
            }}
            store["players"][p["id"]] = {"n": p["name"], "sn": p["name"][:12], "pos": p["pos"], "dob": p["dob"], "h": p["height"], "c": "XXX"}
        scorers = [p for p in playing if p["role"] != "GK"]
        for _ in range(int(scored or 0)):
            s = scorers[int(rng.integers(0, len(scorers)))]
            players[s["id"]]["s"]["goals"] += 1
            pen = rng.random() < 0.1
            incidents.append({"incident_type": "goal", "incident_class": "penalty" if pen else "regular",
                              "time": int(rng.integers(1, 91)), "is_home": is_home, "team": team,
                              "player_name": s["name"], "player_id": int(s["id"])})
        for p in playing:
            if p["role"] == "GK":
                continue
            for _ in range(int(players[p["id"]]["s"]["totalShots"])):
                shots.append({
                    "player_id": int(p["id"]), "player_name": p["name"], "team": team, "is_home": is_home,
                    "x": round(float(np.clip(rng.normal(14, 7), 1, 45)), 1),
                    "y": round(float(np.clip(rng.normal(50, 13), 2, 98)), 1),
                    "xg": round(float(rng.gamma(1.1, 0.09)), 3),
                    "xgot": round(float(rng.gamma(1.0, 0.07)), 3),
                    "shot_type": str(rng.choice(["goal", "save", "miss", "block"])),
                    "body_part": str(rng.choice(["right-foot", "left-foot", "head"])),
                    "situation": str(rng.choice(["regular", "corner", "free-kick", "assisted"])),
                    "time": int(rng.integers(1, 91)),
                })
        if rng.random() < 0.3:
            booked = playing[int(rng.integers(0, len(playing)))]
            incidents.append({"incident_type": "card", "incident_class": "yellow", "time": int(rng.integers(1, 91)),
                              "is_home": is_home, "team": team, "player_name": booked["name"], "player_id": int(booked["id"])})
        sheet[side] = _sheet(rng, team_xg, team_shots)
    store["lineups"][gid] = players
    store["shots"][gid] = shots
    store["incidents"][gid] = sorted(incidents, key=lambda i: i["time"])
    store["momentum"][gid] = [
        {"minute": m, "value": round(float(np.clip(rng.normal(0, 45), -100, 100)), 1)}
        for m in range(0, 91, 5)
    ]
    store["team_stats"][gid] = sheet
    store["lineup_extras"][gid] = {"formation": {"home": "4-3-3", "away": "4-2-3-1"}, "missing": {}}


def build(cfg: LeagueConfig, played_rounds: int = 6, seed: int = 11) -> dict:
    rng = np.random.default_rng(seed)
    teams, confs = team_names(cfg)
    strength = {t: float(rng.uniform(0.85, 1.6)) for t in teams}

    def score(home, away):
        lam_h = strength[home] / strength[away] * 1.25
        lam_a = strength[away] / strength[home]
        return int(rng.poisson(lam_h)), int(rng.poisson(lam_a))

    if cfg.conferences:
        fixtures = []
        for conf, members in confs.items():
            fixtures += _double_round_robin(members)
        fixtures.sort(key=lambda f: f[0])
    else:
        fixtures = _double_round_robin(teams)

    store = _empty_store(cfg.slug, cfg.name, confs)
    prev_start = datetime(2025, 8, 15, tzinfo=timezone.utc)
    cur_start = datetime(2026, 8, 14, tzinfo=timezone.utc)
    gid = 0
    for rnd, home, away in fixtures:
        gid += 1
        hg, ag = score(home, away)
        date = prev_start + timedelta(days=rnd * 7 + int(rng.integers(0, 3)))
        store["matches"][str(gid)] = {
            "home": home, "away": away, "round": rnd, "status": "finished",
            "hs": hg, "as": ag, "date": date.strftime(STAMP),
            "stage": "league", "winner": None, "season_id": 900001,
            "home_id": 5000 + teams.index(home), "away_id": 5000 + teams.index(away),
        }
    for rnd, home, away in fixtures:
        gid += 1
        done = rnd <= played_rounds
        hg, ag = score(home, away) if done else (None, None)
        date = cur_start + timedelta(days=rnd * 7 + int(rng.integers(0, 3)))
        store["matches"][str(gid)] = {
            "home": home, "away": away, "round": rnd,
            "status": "finished" if done else "notstarted",
            "hs": hg, "as": ag, "date": date.strftime(STAMP),
            "stage": "league", "winner": None, "season_id": 900002,
            "home_id": 5000 + teams.index(home), "away_id": 5000 + teams.index(away),
        }

    squads = _squads(teams, rng)
    for gid_s, meta in store["matches"].items():
        if meta["status"] != "finished" or meta["season_id"] != 900002:
            continue
        add_detail(store, gid_s, meta, squads, rng)
    return store


def build_cup(cfg: CupConfig, played_rounds: int = 4, seed: int = 11) -> dict:
    """A synthetic cup store: a swiss league phase, groups, two regional leagues or a knockout bracket, part played."""
    rng = np.random.default_rng(seed)
    teams = [f"{cfg.short_name} Club {i + 1:02d}" for i in range(cfg.n_teams if cfg.kind != "knockout" else 16)]
    strength = {t: float(rng.uniform(0.85, 1.6)) for t in teams}
    countries = ["ENG", "ESP", "ITA", "GER", "FRA", "XXX"]

    def score(home, away):
        lam_h = strength[home] / strength[away] * 1.25
        lam_a = strength[away] / strength[home]
        return int(rng.poisson(lam_h)), int(rng.poisson(lam_a))

    fixtures = []      # (round, home, away, group, stage)
    groups: dict[str, list[str]] = {}
    if cfg.kind == "swiss":
        for rnd in range(1, 9 if cfg.slug != "conference-league" else 7):
            order = rng.permutation(cfg.n_teams)
            for i in range(0, cfg.n_teams, 2):
                fixtures.append((rnd, teams[order[i]], teams[order[i + 1]], None, "league"))
    elif cfg.kind in ("groups", "international"):
        # Groups of four; a national-team tournament's groups play a single round-robin.
        for g in range(cfg.n_groups):
            letter = chr(65 + g)
            members = teams[g * cfg.group_size:(g + 1) * cfg.group_size]
            groups[letter] = members
            legs = _double_round_robin(members)
            for rnd, h, a in (legs if cfg.kind == "groups" else legs[: len(legs) // 2]):
                fixtures.append((rnd, h, a, letter, "league"))
    elif cfg.kind == "regional_swiss":
        for g, region in enumerate(("West", "East")[: cfg.n_groups]):
            members = teams[g * cfg.group_size:(g + 1) * cfg.group_size]
            groups[region] = members
            for rnd in range(1, 9):
                order = rng.permutation(len(members))
                for i in range(0, len(members), 2):
                    fixtures.append((rnd, members[order[i]], members[order[i + 1]], region, "league"))
    elif cfg.kind == "knockout":
        # A Round of 16 fully played over two legs; the quarter-finals, drawn from
        # its winners, are appended below once the results exist.
        order = rng.permutation(16)
        for i in range(0, 16, 2):
            h, a = teams[order[i]], teams[order[i + 1]]
            fixtures.append(("r16", h, a, None, "playoff"))
            fixtures.append(("r16", a, h, None, "playoff"))
    store = _empty_store(cfg.slug, cfg.name, groups)
    start = datetime(2026, 9, 16, tzinfo=timezone.utc)
    for gid, (rnd, home, away, group, stage) in enumerate(fixtures, start=1):
        if cfg.kind == "knockout":
            done = rnd == "r16"
            days = 14 if rnd == "r16" else 60
        else:
            done = rnd <= played_rounds
            days = rnd * 21
        hg, ag = score(home, away) if done else (None, None)
        store["matches"][str(gid)] = {
            "home": home, "away": away, "round": rnd, "status": "finished" if done else "notstarted",
            "hs": hg, "as": ag, "date": (start + timedelta(days=days + (gid % 3))).strftime(STAMP),
            "stage": stage, "winner": None, "season_id": 900002, "group": group,
            "home_id": 5000 + teams.index(home), "away_id": 5000 + teams.index(away),
            "home_country": countries[teams.index(home) % len(countries)],
            "away_country": countries[teams.index(away) % len(countries)],
        }
    # A two-legged tie level on aggregate is settled by Sofascore's aggregate
    # winner code in a real store; here the second-leg host goes through. The
    # winners then make up the next round's drawn, unplayed ties.
    legs: dict[tuple, list[tuple[str, dict]]] = {}
    for gid_s, meta in store["matches"].items():
        if meta["stage"] == "playoff" and meta["status"] == "finished":
            legs.setdefault((meta["round"], frozenset((meta["home"], meta["away"]))), []).append((gid_s, meta))
    winners: list[str] = []
    for pair_legs in legs.values():
        goals: dict[str, int] = {}
        for _, meta in pair_legs:
            goals[meta["home"]] = goals.get(meta["home"], 0) + meta["hs"]
            goals[meta["away"]] = goals.get(meta["away"], 0) + meta["as"]
        last = max(pair_legs, key=lambda kv: kv[1]["date"])[1]
        if len(set(goals.values())) == 1:
            last["agg_winner"] = last["home"]
            winners.append(last["home"])
        else:
            winners.append(max(goals, key=goals.get))
    if cfg.kind == "knockout" and winners:
        gid = len(store["matches"])
        for i in range(0, len(winners) - 1, 2):
            h, a = winners[i], winners[i + 1]
            for home, away, offset in ((h, a, 60), (a, h, 67)):
                gid += 1
                store["matches"][str(gid)] = {
                    "home": home, "away": away, "round": "qf", "status": "notstarted", "hs": None, "as": None,
                    "date": (start + timedelta(days=offset)).strftime(STAMP), "stage": "playoff", "winner": None,
                    "season_id": 900002, "group": None,
                    "home_id": 5000 + teams.index(home), "away_id": 5000 + teams.index(away),
                    "home_country": countries[teams.index(home) % len(countries)],
                    "away_country": countries[teams.index(away) % len(countries)],
                }

    squads = _squads(teams, rng)
    for gid_s, meta in store["matches"].items():
        if meta["status"] == "finished":
            add_detail(store, gid_s, meta, squads, rng)
    return store


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("league", choices=sorted(LEAGUES) + sorted(CUPS))
    parser.add_argument("out", type=Path)
    parser.add_argument("--rounds", type=int, default=6, help="rounds played this season")
    parser.add_argument("--seed", type=int, default=11)
    args = parser.parse_args()

    if args.league in CUPS:
        store = build_cup(CUPS[args.league], args.rounds, args.seed)
    else:
        store = build(LEAGUES[args.league], args.rounds, args.seed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(store, ensure_ascii=False), encoding="utf-8")
    finished = sum(1 for m in store["matches"].values() if m["status"] == "finished")
    print(f"wrote {args.out}: {len(store['matches'])} matches ({finished} finished), "
          f"{len(store['lineups'])} with player detail")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
